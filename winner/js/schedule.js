  // ── Official Export to Excel ──────────────────────────────
  function exportExcel() {
    if (typeof XLSX === 'undefined') {
      showToast('error', 'ไม่พบไลบรารี XLSX');
      return;
    }

    const currentSchedules = _schedules.filter(s => {
      if (_viewType === 'student') return s.group_id === _targetId;
      if (_viewType === 'teacher') return s.teacher_id === _targetId;
      if (_viewType === 'room') return s.room_id === _targetId;
      if (_viewType === 'subject') return s.subject_id === _targetId;
      return true;
    });

    if (currentSchedules.length === 0) {
      showToast('warning', 'ไม่มีข้อมูลตารางสอนที่จะส่งออก');
      return;
    }

    const titleRow = [`ตารางเรียนและตารางสอน EduSched AI (วิทยาลัยเทคนิค/อาชีวศึกษา) - ภาคเรียนที่ 1 ปีการศึกษา 2568`];
    const subRow = [`มุมมอง: ${_viewType} | รหัสเป้าหมาย: ${_targetId || 'ทั้งหมด'} | วันที่ส่งออก: ${new Date().toLocaleDateString('th-TH')}`];
    const header = ['วัน/เวลา', '07:45-08:00', '08:00-09:00', '09:00-10:00', '10:00-11:00', '11:00-12:00', '12:00-13:00', '13:00-14:00', '14:00-15:00', '15:00-16:00', '16:00-17:00', '17:00-18:00', '18:00-19:00', '19:00-20:00'];
    const rows = [titleRow, subRow, [], header];

    DAYS.forEach(day => {
      const dayShort = day.replace('วัน', '');
      const row = [day, '', '', '', '', '', 'พักกลางวัน', '', '', '', '', '', '', ''];

      currentSchedules.filter(s => s.day === day || s.day === dayShort).forEach(s => {
        const text = `${s.subject_id} (${s.room_id || ''} ${s.teacher_id || ''})`;
        if (s.period_start === 0) {
          row[1] = text;
        } else {
          for (let p = s.period_start; p <= s.period_end; p++) {
            const colIdx = p <= 4 ? p + 1 : p + 2;
            if (colIdx < row.length) {
              row[colIdx] = text;
            }
          }
        }
      });

      rows.push(row);
    });

    const ws = XLSX.utils.aoa_to_sheet(rows);
    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, ws, 'ตารางสอน');

    const fileName = `EduSched_Timetable_${_targetId || 'All'}.xlsx`;
    XLSX.writeFile(wb, fileName);
    showToast('success', 'ส่งออกสำเร็จ', `บันทึกเป็น ${fileName}`);
  }

  // ── Official Export to CSV with UTF-8 BOM ───────────────────
  function exportCSV() {
    const currentSchedules = _schedules.filter(s => {
      if (_viewType === 'student') return s.group_id === _targetId;
      if (_viewType === 'teacher') return s.teacher_id === _targetId;
      if (_viewType === 'room') return s.room_id === _targetId;
      if (_viewType === 'subject') return s.subject_id === _targetId;
      return true;
    });

    if (currentSchedules.length === 0) {
      showToast('warning', 'ไม่มีข้อมูลตารางสอนที่จะส่งออก');
      return;
    }

    const headers = ['ลำดับ', 'วัน', 'คาบเริ่มต้น', 'คาบสิ้นสุด', 'รหัสวิชา', 'ครูผู้สอน', 'ห้องเรียน', 'กลุ่มเรียน'];
    const rows = [headers];

    currentSchedules.forEach((s, idx) => {
      rows.push([
        idx + 1,
        s.day,
        s.period_start,
        s.period_end,
        `"${s.subject_id}"`,
        `"${s.teacher_id}"`,
        `"${s.room_id}"`,
        `"${s.group_id}"`
      ]);
    });

    const csvContent = '\uFEFF' + rows.map(e => e.join(',')).join('\n');
    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const link = document.createElement('a');
    const url = URL.createObjectURL(blob);
    link.setAttribute('href', url);
    link.setAttribute('download', `EduSched_Timetable_${_targetId || 'All'}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    showToast('success', 'ส่งออกสำเร็จ', 'บันทึกเป็นไฟล์ CSV เรียบร้อยแล้ว');
  }

