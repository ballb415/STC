  function normalizeDay(d) {
    if (!d) return 'วันจันทร์';
    const map = {
      'MON': 'วันจันทร์', 'จันทร์': 'วันจันทร์', 'วันจันทร์': 'วันจันทร์',
      'TUE': 'วันอังคาร', 'อังคาร': 'วันอังคาร', 'วันอังคาร': 'วันอังคาร',
      'WED': 'วันพุธ', 'พุธ': 'วันพุธ', 'วันพุธ': 'วันพุธ',
      'THU': 'วันพฤหัสบดี', 'พฤหัสบดี': 'วันพฤหัสบดี', 'วันพฤหัสบดี': 'วันพฤหัสบดี',
      'FRI': 'วันศุกร์', 'ศุกร์': 'วันศุกร์', 'วันศุกร์': 'วันศุกร์'
    };
    return map[d] || d;
  }

  function checkManualConflict() {
    const teacherId = document.getElementById('modal-teacher')?.value;
    const roomId = document.getElementById('modal-room')?.value;
    const groupId = document.getElementById('modal-group')?.value;
    const dayRaw = document.getElementById('modal-day')?.value;
    const day = normalizeDay(dayRaw);
    const start = parseInt(document.getElementById('modal-start')?.value, 10);
    const periods = parseInt(document.getElementById('modal-periods')?.value, 10) || 1;
    let end = isNaN(start) ? NaN : (start === 0 ? 0 : start + periods - 1);
    if (document.getElementById('modal-end')?.value) {
      const eVal = parseInt(document.getElementById('modal-end')?.value, 10);
      if (!isNaN(eVal)) end = eVal;
    }

    const alertBox = document.getElementById('modal-conflict-warning') || document.getElementById('modal-conflict-alert');
    if (!alertBox) return [];

    if (isNaN(start) || isNaN(end) || !day) {
      alertBox.classList.add('hidden');
      return [];
    }

    const clashes = [];

    // Check lunch overlap (start in morning 1..4, and extends into afternoon >=5)
    if (start > 0 && start <= 4 && end >= 5) {
      clashes.push(`คาบเรียนข้ามช่วงพักกลางวัน (12:00 - 13:00) [Hard Constraint 7]`);
    }

    // Check with existing schedules
    for (const s of _schedules) {
      const sDay = normalizeDay(s.day);
      if (sDay !== day) continue;

      // Overlap condition
      const overlap = Math.max(start, s.period_start) <= Math.min(end, s.period_end);
      if (!overlap) continue;

      if (teacherId && s.teacher_id === teacherId) {
        clashes.push(`ครู ${teacherId} มีสอนวิชา ${s.subject_id} ในห้อง ${s.room_id} อยู่แล้ว (คาบ ${s.period_start}-${s.period_end})`);
      }
      if (roomId && s.room_id === roomId) {
        clashes.push(`ห้อง ${roomId} ถูกใช้งานโดยวิชา ${s.subject_id} อยู่แล้ว (คาบ ${s.period_start}-${s.period_end})`);
      }
      if (groupId && s.group_id === groupId) {
        clashes.push(`กลุ่ม ${groupId} มีเรียนวิชา ${s.subject_id} อยู่แล้ว (คาบ ${s.period_start}-${s.period_end})`);
      }
    }

    if (clashes.length > 0) {
      alertBox.innerHTML = `<strong><i class="fas fa-triangle-exclamation"></i> พบข้อขัดแย้ง:</strong><br>` + clashes.map(c => `• ${c}`).join('<br>');
      alertBox.classList.remove('hidden');
    } else {
      alertBox.classList.add('hidden');
    }

    return clashes;
  }

