  function onModalSubjectChange() {
    const subjSel = document.getElementById('modal-subject') || document.getElementById('modal-subj');
    const teacherSel = document.getElementById('modal-teacher');
    const roomSel = document.getElementById('modal-room');
    const periodsInput = document.getElementById('modal-periods');
    const startSel = document.getElementById('modal-start');
    if (!subjSel) return;

    const subjId = subjSel.value;
    const subj = _subjects.find(s => s.subject_id === subjId);

    // Auto-select periods: practical = 2 or practice hours, theory = 1 or 2
    if (subj && periodsInput) {
      if (subj.subject_id === 'HOMEROOM' || startSel?.value === '0') {
        periodsInput.value = '1';
      } else if (subj.practice && subj.practice >= 2) {
        periodsInput.value = '2';
      } else {
        periodsInput.value = String(Math.max(1, subj.theory || 1));
      }
    }

    // Auto-select teacher from teaching loads if assigned
    if (subjId && teacherSel && (!teacherSel.value || _viewType !== 'teacher')) {
      const load = _teachingLoads.find(l => l.subject_id === subjId);
      if (load && load.teacher_id) {
        teacherSel.value = load.teacher_id;
      }
    }

    // Auto-suggest room (Lab room for practical subjects, lecture for others)
    if (subj && roomSel && (!roomSel.value || _viewType !== 'room')) {
      const isLab = (subj.practice && subj.practice > 0) || !subj.subject_id.startsWith('20');
      const preferredRoom = _rooms.find(r => isLab ? (r.room_type?.includes('ปฏิบัติ') || r.room_id?.startsWith('LAB')) : !r.room_id?.startsWith('LAB'));
      if (preferredRoom) {
        roomSel.value = preferredRoom.room_id;
      } else if (_rooms.length > 0 && !roomSel.value) {
        roomSel.value = _rooms[0].room_id;
      }
    }

    checkManualConflict();
  }

